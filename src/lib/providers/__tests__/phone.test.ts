import { describe, it, expect } from "vitest";
import { toE164 } from "../phone";

describe("toE164", () => {
  it.each([
    ["+14084269127", "+14084269127"],
    ["4084269127", "+14084269127"],
    ["(408) 426-9127", "+14084269127"],
    ["408.426.9127", "+14084269127"],
    ["1 408 426 9127", "+14084269127"],
    ["+44 20 7946 0958", "+442079460958"],
    ["0044 20 7946 0958", "+442079460958"],
    [" +1-408-426-9127 ", "+14084269127"],
  ])("normalizes %s", (input, expected) => {
    expect(toE164(input)).toBe(expected);
  });

  it.each(["", "abc", "408-426-9127, 408-426-9128", "123", "+1408426912712345", "4084269127;4084269128"])(
    "rejects %s",
    (input) => {
      expect(toE164(input)).toBeNull();
    }
  );
});
